import { expect, test } from '@playwright/test'

import { PASSWORD, USERNAME, createTransaction, login, monthParam, navigate, unique } from './helpers'

test('login: senha errada mostra o motivo e a certa abre o painel', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Usuário').fill(USERNAME)
  await page.getByLabel('Senha').fill('senha-errada')
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('alert')).toHaveText('Usuário ou senha incorretos.')
  await page.getByLabel('Senha').fill(PASSWORD)
  await page.getByRole('button', { name: 'Entrar' }).click()
  await expect(page.getByRole('heading', { name: 'Painel' })).toBeVisible()
})

test('compra parcelada no cartão aparece na lista, na fatura e no limite', async ({ page }) => {
  await login(page)
  const cardName = unique('Cartão')
  await navigate(page, 'Cartões')
  await page.getByRole('button', { name: 'Novo cartão' }).first().click()
  const cardForm = page.getByRole('dialog')
  await cardForm.getByLabel('Nome do cartão').fill(cardName)
  await cardForm.getByLabel('Limite').fill('3.000,00')
  await cardForm.getByLabel('Dia do fechamento').fill('10')
  await cardForm.getByLabel('Dia do vencimento').fill('17')
  await cardForm.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('Cartão cadastrado.')).toBeVisible()

  await navigate(page, 'Lançamentos')
  await page.getByRole('button', { name: 'Novo lançamento' }).first().click()
  const form = page.getByRole('dialog')
  const description = unique('Notebook')
  await form.getByLabel('Descrição').fill(description)
  await form.getByLabel('Valor').fill('1.200,00')
  await form.getByLabel('Categoria').selectOption({ label: '📱 Eletrônicos' })
  await form.getByLabel('Forma de pagamento').selectOption('credit_card')
  await form.getByLabel('Cartão').selectOption({ label: cardName })
  await form.getByLabel('Parcelas').fill('3')
  await expect(form.getByText('3× de R$ 400,00')).toBeVisible()
  await form.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('Compra lançada em 3 parcelas.')).toBeVisible()
  const row = page.getByRole('row', { name: new RegExp(description) })
  await expect(row).toContainText('1/3')
  await expect(row).toContainText('R$ 400,00')

  await navigate(page, 'Cartões')
  const card = page.locator('[data-slot="card"]', { hasText: cardName })
  await expect(card).toContainText('R$ 1.200,00 de R$ 3.000,00')
  await card.getByRole('button', { name: 'Ver faturas' }).click()
  await expect(page.getByRole('dialog')).toContainText(description)
})

