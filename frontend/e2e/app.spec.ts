test('fixa aparece prevista no painel e é confirmada uma única vez', async ({ page }) => {
  await login(page)
  await navigate(page, 'Fixas')
  await page.getByRole('button', { name: 'Nova fixa' }).first().click()
  const form = page.getByRole('dialog')
  const description = unique('Internet')
  await form.getByLabel('Descrição').fill(description)
  await form.getByLabel('Valor').fill('99,90')
  await form.getByLabel('Dia do mês').fill('15')
  await form.getByLabel('Categoria').selectOption({ label: '🏠 Moradia' })
  await form.getByRole('button', { name: 'Salvar' }).click()
  await expect(page.getByText('Fixa criada.')).toBeVisible()

  await navigate(page, 'Painel')
  const confirmRequests: string[] = []
  page.on('request', (request) => request.url().includes('/confirm') && confirmRequests.push(request.url()))
  const confirm = page.getByRole('button', { name: `Confirmar ${description}` })
  await confirm.dblclick()
  await expect(page.getByText(`“${description}” confirmada.`)).toBeVisible()
  await expect(confirm).toHaveCount(0)
  await expect(page.getByText(/conflita|já foi confirmada/)).toHaveCount(0)
  expect(confirmRequests).toHaveLength(1)
  await navigate(page, 'Lançamentos')
  await expect(page.getByRole('row', { name: new RegExp(description) })).toHaveCount(1)
})

test('voltar no navegador mantém o mês escolhido', async ({ page }) => {
  await login(page)
  const previous = monthParam(-1)
  await page.getByRole('button', { name: 'Mês anterior' }).click()
  await expect(page).toHaveURL(new RegExp(`\\?mes=${previous}`))
  await navigate(page, 'Lançamentos')
  await expect(page).toHaveURL(new RegExp(`/lancamentos\\?mes=${previous}`))
  await page.goBack()
  await expect(page).toHaveURL(new RegExp(`/\\?mes=${previous}`))
  await expect(page.getByRole('heading', { name: 'Painel' })).toBeVisible()
})

test('sessão expirada leva ao login com aviso', async ({ page, context }) => {
  await login(page)
  // O Painel ainda busca alertas, tetos e previsão depois do título aparecer; sem esperar, uma dessas respostas
  // pode chegar já sem sessão e levar ao login antes do clique abaixo.
  await page.waitForLoadState('networkidle')
  await context.clearCookies()
  // Precisa de uma requisição nova: dados já carregados continuam em cache por alguns segundos.
  await page.getByRole('button', { name: 'Mês anterior' }).click()
  await expect(page.getByRole('alert')).toContainText('Sua sessão expirou')
  await expect(page.getByRole('button', { name: 'Entrar' })).toBeVisible()
})

